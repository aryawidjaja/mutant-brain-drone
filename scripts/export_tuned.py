"""Tuned arbiter parameters (and the yaw-circuit surrogate fit) -> app/data/tuned_params.js for the live simulator.

Study 1 brain (v1): results/tuned3d_params.json when it exists (frozen 3D tuning), else results/kt2_tuned_params.json
-> window.TUNED = {_source, <arm>: params}.
Study 2 brain (v2, the app's default): results/tuned_v2_params.json (frozen before any v2 test seed; the six arbiters
on the v2 stack, ring = RingGated) -> window.TUNED_V2 = {_source, <arm>: params, _heading: {ring, kf, cf: params},
_heading_source}; the heading estimators' parameters come from results/kt5_tuned_params.json, as in scripts/run_v2.py.
window.YAW_SURROGATE = {K, tau_s, wc_radps, fit errors, _source} from results/yaw_surrogate.json.
Usage: uv run python scripts/export_tuned.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "app/data/tuned_params.js"
ARMS = ["ring", "ring_static", "vote", "sum", "accumulator", "state_machine"]


def build():
    src = next(p for p in ("results/tuned3d_params.json", "results/kt2_tuned_params.json") if (ROOT / p).exists())
    arms = json.loads((ROOT / src).read_text())["arms"]
    tuned = {"_source": src, **{a: arms[a]["params"] for a in ARMS if a in arms}}
    v2 = json.loads((ROOT / "results/tuned_v2_params.json").read_text())
    hd = json.loads((ROOT / "results/kt5_tuned_params.json").read_text())["estimators"]
    tuned_v2 = {"_source": "results/tuned_v2_params.json", **{a: v2["arms"][a]["params"] for a in ARMS},
                "_heading": {e: hd[e]["params"] for e in ("ring", "kf", "cf")}, "_heading_source": "results/kt5_tuned_params.json"}
    y = json.loads((ROOT / "results/yaw_surrogate.json").read_text())
    yaw = {k: y[k] for k in ("K", "tau_s", "wc_radps", "fc_hz", "rms_gain_err_db", "rms_phase_err_deg")}
    yaw["_source"] = "results/yaw_surrogate.json"
    return tuned, tuned_v2, yaw


if __name__ == "__main__":
    tuned, tuned_v2, yaw = build()
    OUT.write_text("// Generated by scripts/export_tuned.py. Do not edit.\n"
                   f"window.TUNED = {json.dumps(tuned, indent=1)};\nwindow.TUNED_V2 = {json.dumps(tuned_v2, indent=1)};\n"
                   f"window.YAW_SURROGATE = {json.dumps(yaw, indent=1)};\n")
    # self-check: the file parses back to the same values, every arm is present, and params are plain numbers
    txt = OUT.read_text()
    back = json.loads(txt.split("window.TUNED = ", 1)[1].split(";\nwindow.TUNED_V2", 1)[0])
    back2 = json.loads(txt.split("window.TUNED_V2 = ", 1)[1].split(";\nwindow.YAW_SURROGATE", 1)[0])
    assert back == tuned and set(ARMS) <= set(back), sorted(back)
    assert back2 == tuned_v2 and set(ARMS) <= set(back2), sorted(back2)
    assert all(isinstance(v, (int, float)) for t in (back, back2) for a in ARMS for v in t[a].values())
    assert abs(back2["ring"]["ring_gain"] - 0.6862567466828404) < 1e-12           # the frozen v2 ring (RingGated)
    assert set(back2["_heading"]) == {"ring", "kf", "cf"} and back2["_heading"]["ring"]["w_sun"] > 0
    assert yaw["K"] > 0 and yaw["tau_s"] >= 0 and yaw["wc_radps"] > 0
    print(f"{OUT.relative_to(ROOT)} written from {tuned['_source']} and {tuned_v2['_source']}: v1 " + ", ".join(f"{a} {len(tuned[a])}" for a in ARMS)
          + "; v2 " + ", ".join(f"{a} {len(tuned_v2[a])}" for a in ARMS) + " params")
