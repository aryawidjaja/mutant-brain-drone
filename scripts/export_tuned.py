"""Tuned arbiter parameters (and the yaw-circuit surrogate fit) -> app/data/tuned_params.js for the live simulator.

Reads results/tuned3d_params.json when it exists (frozen 3D tuning), else results/kt2_tuned_params.json (2D kill-test
tuning, a stand-in until the 3D tuning lands). Writes window.TUNED = {_source, <arm>: params} and
window.YAW_SURROGATE = {K, tau_s, wc_radps, fit errors, _source} from results/yaw_surrogate.json.
Usage: uv run python scripts/export_tuned.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "app/data/tuned_params.js"
ARMS = ["ring", "ring_static", "vote", "sum", "accumulator", "state_machine"]


def build():
    src = next(p for p in ("results/tuned3d_params.json", "results/kt2_tuned_params.json") if (ROOT / p).exists())
    arms = json.loads((ROOT / src).read_text())["arms"]
    tuned = {"_source": src, **{a: arms[a]["params"] for a in ARMS if a in arms}}
    y = json.loads((ROOT / "results/yaw_surrogate.json").read_text())
    yaw = {k: y[k] for k in ("K", "tau_s", "wc_radps", "fc_hz", "rms_gain_err_db", "rms_phase_err_deg")}
    yaw["_source"] = "results/yaw_surrogate.json"
    return tuned, yaw


if __name__ == "__main__":
    tuned, yaw = build()
    OUT.write_text("// Generated by scripts/export_tuned.py. Do not edit.\n"
                   f"window.TUNED = {json.dumps(tuned, indent=1)};\nwindow.YAW_SURROGATE = {json.dumps(yaw, indent=1)};\n")
    # self-check: the file parses back to the same values, every arm is present, and params are plain numbers
    txt = OUT.read_text()
    back = json.loads(txt.split("window.TUNED = ", 1)[1].split(";\nwindow.YAW_SURROGATE", 1)[0])
    assert back == tuned and set(ARMS) <= set(back), sorted(back)
    assert all(isinstance(v, (int, float)) for a in ARMS for v in back[a].values())
    assert yaw["K"] > 0 and yaw["tau_s"] >= 0 and yaw["wc_radps"] > 0
    print(f"{OUT.relative_to(ROOT)} written from {tuned['_source']}: " + ", ".join(f"{a} {len(tuned[a])} params" for a in ARMS))
